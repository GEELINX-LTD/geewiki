-- 0020_version_title.sql —— 版本快照补上「改前的标题」
--
-- 给 `page_versions` 增一列：
--   title —— **该快照当时的标题**（NULL = 本迁移之前的历史行）
--
-- ★★ **为什么单独一支迁移，而不是并进 0019**：
--   0019 已经在实机上应用过（`_migrations` 里有记录），迁移器按"跑过就不再跑"工作 ——
--   往 0019 里追加 ALTER 对**已升级的库**永远不会生效，于是出现"代码查 `v.title`、
--   库里没这列"的 500（本次就是这样撞出来的）。迁移是**append-only 的历史**，
--   已经发布过的那一支只能保持原样，补列必须新开一支。
--
-- ★ **为什么需要它**（`content` 之外的另一半）：
--   保存路径允许"只改标题"与"标题正文一起改"。只快照正文的话，时间线上会出现
--   一次「正文未变」的改动（`statsLabel` 会给"正文未变"），用户读到的是
--   "什么都没改却多了一版" —— 而那一次真正改的是标题。存下来才能如实说清。
--
-- ★ **为什么允许 NULL，且读侧不下结论**：
--   0020 之前的行没有这一列的值。界面此时**只显示正文差异**，不对标题做任何断言
--   （`null` 与"标题为空串"是两回事：后者是"标题被清空了"，那是真实改动）。
ALTER TABLE page_versions ADD COLUMN title TEXT;
