-- 0024_block_author.sql —— 内容块承载「谁改的」（块级归属）
--
-- 给 `blocks` 增一列：
--   updated_by —— 最后一次**改动这个块文本**的主体 user id（NULL = 无法归属，见下）
--
-- ★★ **为什么要它**（现状的缺口）：
--   `blocks` 一直有 `created_at` / `updated_at`，但**没有作者**。而 0019 给
--   `page_versions` 补 `saved_by` 时已经把话说清楚了：「"谁编辑了正文"在本仓库里查不到」。
--   0019 补的是**页级**（每次保存的触发者，进版本时间线）；本支补的是**块级**——
--   一页里这一段和那一段**不是同一个人改的**，页级字段回答不了"这一段是谁写的"，
--   读者也就只能看到"整页最近被谁动过"。
--
-- ★ **与 `page_versions.saved_by` 的三条约定逐条一致**（不是巧合，是同一件事的块级版本）：
--   1. **无外键**：与 `pages.created_by` / `pages_versions.saved_by` 同款理由（见 0012 注释）
--      —— 用户被删除后条目与历史必须留存，外键会把删用户变成删内容归属；
--      因此 id 可能指向一个已不存在的用户，读侧按"查不到就当未知"处理。
--   2. **允许 NULL**：`syncBlocksForPage` 是**跨插件服务路径**（内置文档同步、AI 代写、
--      存量回填都会经过它），这类写入没有可归属的主体，写 NULL 比编一个假 id 诚实；
--      读侧据 NULL **不显示任何归属**（而不是显示"某个人"或"未记录"）。
--   3. **记的是"这次改动的触发者"**，与 `updated_at` **同一时刻**写入 —— 所以读侧
--      把「谁 + 什么时候」当成一条改动来用是成立的。
--
-- ★★ **语义收紧（本条是本次改动的要害）**：`updated_at` 从"这一页被保存过"改成
--   **"这个块的文本真的变了"**。在此之前 `syncBlocksForPage` 的 UPDATE 分支**无条件**
--   写 `updated_at = now`，于是复用旧 id 的块即使一个字都没改，时间戳也会被刷新 ——
--   那个值只能回答"页面最近保存于"，拿它当"这一段最近被编辑于"就是**撒谎**
--   （未改动的块会被说成刚刚被改过）。现在：文本没变 ⇒ 两列**都不写**（保留原值），
--   文本变了或新插入 ⇒ 两列一起写成"这次 + 这个人"。
--   ⚠️ 由此产生的历史口径：本迁移**之前**写入的块行，其 `updated_at` 是最后一次页面保存
--   的时刻（可能晚于该块真实的最后改动），且 `updated_by` 为 NULL ⇒ 读侧**不显示归属**，
--   直到该块下次真的被改动。这里刻意**不回填**：没有可靠来源可以回填出一个正确的作者，
--   编一个比留空更坏。
--
-- ★ 落点与 0015 一致：`blocks` 由 db 插件的迁移建立（理由见 0015 的落点说明），
--   故本支也落在 db 包、**两侧方言成对**。
--
-- 约定同前：**不写 BEGIN/COMMIT**（控制器逐文件包事务）。含 `ADD COLUMN`，
-- 在 SQLite 上**不可重放**（没有 `ADD COLUMN IF NOT EXISTS`）—— 生产幂等性由
-- `_migrations` 控制器提供（已应用的文件不再执行），重放守卫测试按形状分类。
ALTER TABLE blocks ADD COLUMN updated_by INTEGER;
