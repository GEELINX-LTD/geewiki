-- 0019_version_author.sql —— 版本快照承载「谁改的」与「改前的标题」
--
-- 给 `page_versions` 增两列：
--   saved_by —— 触发这次改动的主体 user id（NULL = 匿名/无法归属，见下）
--   title    —— **该快照当时的标题**（NULL = 0019 之前的历史行，见下）
--
-- ★★ **为什么要它**（现状的缺口）：
--   在此之前，`page_versions` 只有 `(id, page_id, content, saved_at, blocks_json, acl_json)`
--   —— 也就是**只有"什么时候"和"改成了什么"，没有"谁改的"**。而 `pages` 上的
--   `created_by`（0012 加的）**从未被写入过**（保存路径不维护它），审计表又只覆盖
--   ACL/权限类动作（`acl.change` / `access.denied` / `attachment.*`），正文保存与
--   页面删除都不写审计。三处合起来的结论是：**"谁编辑了正文"在本仓库里查不到**，
--   而这正是"每次改动如何体现出来"的一半。
--
-- ★ 语义与写入时机：`saved_by` 记录的是**这次保存/恢复/可见性写入的触发者**
--   （与 `saved_at` 同一时刻），不是"快照内容的作者" —— 快照存的是**改动前**的状态，
--   所以作者列与内容列在时间上并不指同一次动作。这是刻意的：把"谁做了这次改动"
--   钉在这一行上，读侧就能把「时间 + 作者 + 这次改了哪几行」三者对齐。
--
-- ★ **为什么不加外键**：与 `pages.created_by` 同款理由（见 0012 的注释）——
--   用户被删除后条目与历史必须留存（历史资产），外键会把删用户变成删历史。
--   因此 id 可能指向一个已不存在的用户；读侧按"查不到就当未知"处理。
--
-- ★ **为什么允许 NULL**：`wiki-service.save()` 是**跨插件服务契约**，其它插件可代调用
--   （不经过 HTTP 主体）。这类调用没有可归属的用户，写 NULL 比编一个假 id 诚实；
--   界面据 NULL 显示「未知」而不是「某个人」。
--
-- ★ 标题那一半（`title` 列）**不在这里**：见 `0020_version_title.sql`。
--   原因不只是"本支已应用过"——迁移是 append-only 的历史，补列一律新开一支。
ALTER TABLE page_versions ADD COLUMN saved_by INTEGER;
