-- 0021_version_origin.sql —— 版本快照承载「这次改动是什么性质」
--
-- 给 `page_versions` 增一列：
--   origin —— 产生这一版的动作类别：'content' | 'acl' | NULL
--
-- ★★ **为什么需要它**（把版本号读懂的前提）：
--   `snapshotAclVersion()` 的存在意味着**每次改权限也会产生一条版本**（正文不变、
--   只是 `acl_json` 变了）。于是「版本号增长」≠「正文被编辑过」—— 用户看到 v20 却
--   想不出自己改过 20 次正文，因为其中一半是发布/撤销发布/加授权留下的。
--   不记来源的话，界面只能把所有版本都显示成"改动"，那是在编造。
--
-- ★ 取值与写入点（写入侧唯一公共路径是 `snapshotAclVersion`，见 index.ts 的注释）：
--   'content' —— 正文保存、恢复正文快照、新建页面（create 分支的裸 INSERT）
--   'acl'     —— 改档位 / 发布 / 撤发布 / 发与撤授权 / 访问申请批准（这些都只动权限）
--   NULL      —— 0021 之前写入的历史行。**语义是"升级前"，不是"未知"** ——
--                这些行确实存在，只是当时没有这个字段可记。
--
-- ★ **为什么不加 CHECK 约束**：与 0017/0019 一致 —— 约束一旦写进 DDL，将来新增
--   一类来源（例如"由导入脚本产生"）就必须再开一支迁移去改约束；而这一列是**只读
--   展示用**的元数据，非法值最坏的后果是界面显示得笼统，不是数据损坏。
--
-- ★ **为什么可空、默认 NULL**：回滚策略是"回滚应用代码、保留列" —— 恢复旧代码后
--   没有写入方，新列留 NULL 无害；反之若不许可空，回滚就会因缺值而失败。
--
-- ★ 方言边界：SQLite **没有** `ADD COLUMN IF NOT EXISTS`，本文件**无法重放**
--   （重放会 `duplicate column name: origin`）。生产幂等性由 `_migrations` 控制器
--   提供（已应用的文件不再执行），`slug-hierarchy.test.ts` 已把这条边界钉死。
ALTER TABLE page_versions ADD COLUMN origin TEXT;
