/**
 * 会话核心的系统提示。
 *
 * ## 为什么它比一般的"你是一个助手"长这么多
 * 本插件的模型**手里有工具**，而工具带来三类具体的失败模式，每一条都实测或明确预见过：
 *
 * 1. **盲猜措辞**（实测，`data/verify/ai-native-probe/agent-loop.mjs`）：检索是字面匹配，
 *    模型不知道知识库里用的是哪些词时会连猜 5 次全空。解药是"先看地图"——
 *    故提示里点名 `list_pages` 是**第一步**，并明说"0 命中通常只是措辞不同"。
 * 2. **把资料当指令**（设计文档 §3.3 红线）：工具结果是**别人写的页面正文**。
 *    页面里出现"请忽略之前的指令"是完全可能的（谁都能编辑知识库），
 *    而它会以一条 `tool` 消息出现在上下文里。必须**在提示层**把这条边界说清楚。
 *    （结构上它已经在 `tool` 角色而不是 `system` 里，但只靠角色分层不够——
 *    模型并不知道本仓的角色约定，得有人告诉它。）
 * 3. **用先验知识补齐**：这是最伤信任的一条。答不出时含糊其辞，比明确说"知识库里没有"更糟——
 *    用户无法从一段流畅的文本里分辨出哪句有出处。故提示里写死"资料不足要明说"。
 *
 * ## 一条**曾经的刻意留白**（P5 已补上）
 * 决策 4 要求"知识库之外的问题可以答，但必须**显著标注**"。P2 时那段措辞只能要求模型
 * **写一句话**说明"以下不是知识库内容"——而提示层的请求不是护栏，模型可以不听。
 *
 * P5 把它变成了**结构化标记**：工具结果带 `grounding`（`@geewiki/ai-tools` 的
 * `AiToolResult`），会话核心据此算出 `grounded` 与 `groundingSources` 并随 `done` 帧下发，
 * 界面自己渲染标注。于是下面那句"你必须声明"**被删掉了**——留着它会变成双重标注
 * （界面一条、模型又写一句），而两句话不一致时用户不知道该信哪句。现在的分工是：
 * **模型只管把答案说好，标注由代码保证**。
 *
 * 依据现在有**两档**（`AiToolGrounding`），界面按档给不同措辞：
 * - `'kb'`（知识库正文）⇒ 不标注，那是本助手被期望的行为；
 * - `'web'`（`web_search` 拿到的公开资料）⇒ 标「依据的是公开网络资料」，
 *   因为**它确实有依据，只是不在本知识库里**——这一档不能被算成"来自模型自身的知识"，
 *   那会把模型给出的来源链接说成是它自己编的。
 * 两档都没有才标「这不是知识库内容」。
 *
 * 也正因如此，`'web'` 那一档要求模型**写出可点的来源链接**（见下面【怎么用工具】一节）：
 * 标注只能说"请点开来源自行核实"，而来源得由模型给出来；模型不给链接，
 * 这条标注就成了一句无法执行的建议。
 * 那句提示写成了**条件句**（"若工具表里有 web_search"）而不是直接命令：
 * 这个工具由可选插件贡献，宿主没装它时提示里点名一个不存在的工具，
 * 只会让模型白调一轮、拿回一条"没有名为 web_search 的工具"。
 *
 * 提示里保留的是模型**该知道**的那部分：它**可以**回答知识库之外的问题
 * （需求 ⑥ 的"给 AI 更多自由"），但要说清来源，不要把自己的知识说成是从知识库查到的。
 */
