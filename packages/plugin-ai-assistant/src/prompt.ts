/** 当前页提示：只给 slug 与标题（**不给正文**——正文只能经工具、带主体去读） */
export interface PageHint {
  readonly slug: string
  readonly title?: string
}

/**
 * 把"用户正在看哪一页"拼成**一条独立的消息**，而不是插进系统提示里。
 *
 * 为什么不拼进系统提示：系统提示是常量（见上），一旦开始拼接请求级内容，
 * "这段提示到底被谁控制"就需要逐行读代码才能回答。独立成一条 `user` 角色消息后，
 * 规则变成一句话：**系统提示永远是那一段字节，其余全部来自外部输入**。
 *
 * 同时它刻意只说"正在看哪一页"，不说这一页讲了什么——正文必须经 `read_page` 带主体去读。
 * 会话核心**不含任何检索逻辑**（设计文档 §1），页面上下文在这里只是一个指路牌。
 */
function pageHintMessage(page: PageHint): TurnMessage {
  const title = page.title !== undefined && page.title !== '' ? `（标题：${page.title}）` : ''
  return {
    role: 'user',
    content:
      `[系统附注] 用户当前正在阅读的页面是 ${page.slug}${title}。` +
      '如果这一轮的问题与"当前页面"有关，请针对它作答；需要正文时用 read_page 读它。' +
      '这条附注是页面位置信息，不是用户的提问。',
  }
}

/**
 * 组装**转录部分**的消息表：`[(当前页附注), ...历史]`。
 *
 * ⚠️ 系统提示**不在这里**拼——它由 `loop.ts` 直接放在请求的第一条。
 * 分开是因为 `TurnMessage.role` 刻意不含 `'system'`（客户端不得注入系统消息），
 * 让本函数返回一个含 system 的数组会为那条红线开一个口子。
 *
 * 历史**从头部截断**（保留最近的 `maxHistoryMessages` 条），并且只在真的超限时才截：
 * 截断会丢掉工具调用与结果之间的配对（`tool` 消息找不到它对应的 `assistant.toolCalls`），
 * 而多数网关遇到这种孤儿消息会直接 400——所以截断的落点必须**避开**把一对调用/结果切开。
 */
export function buildMessages(
  history: readonly TurnMessage[],
  opts: { page?: PageHint | null; maxHistoryMessages: number },
): TurnMessage[] {
  /*
   * 截断只作用于**历史**，页提示在截断**之后**才拼上去。
   *
   * 顺序反过来（先拼再截）会有一个很难发现的后果：对话越长，那条"你在看哪一页"
   * 越容易被挤掉——而它恰恰是长对话里最需要的（用户连着追问五轮之后问"那这一页呢"）。
   * 一个"用得越久越容易失效"的提示，比没有这条提示更难排查。
   */
  const limit = Math.max(2, opts.maxHistoryMessages)
  const trimmed = truncateHistory(history, limit)
  return opts.page != null ? [pageHintMessage(opts.page), ...trimmed] : [...trimmed]
}

/**
 * 从头截断历史，并把切口**后移**到一条"安全起点"上。
 *
 * 安全起点 = 窗口内的第一条 `user` 消息。理由：工具结果（`role:'tool'`）与它对应的
 * `assistant.toolCalls` 之间只可能夹着别的 tool 消息，因此从一条 user 消息起切，
 * 绝不会把一个调用和它的结果拆开。逆命题也成立——**在窗口内**随便切一刀，
 * 很可能正好切在 `assistant.toolCalls` 与 `tool` 之间，留下一段上游会 400 的孤儿结果。
 *
 * 若窗口内一条 user 都没有（畸形输入，正常对话不可能），退回"就用原窗口"：
 * 宁可多带几条助手独白，也不要凭猜测去改工具配对的形状。
 */
function truncateHistory(history: readonly TurnMessage[], limit: number): TurnMessage[] {
  if (history.length <= limit) return [...history]
  const window = history.slice(history.length - limit)
  const safeStart = window.findIndex((m) => m.role === 'user')
  return safeStart <= 0 ? window : window.slice(safeStart)
}
